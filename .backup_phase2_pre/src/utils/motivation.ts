/**
 * Returns a motivational phrase tailored to the question number and progress.
 */
export function getMotivationalPhraseForQuestion(questionNumber: number, totalQuestions: number = 30): MotivationalPhrase {
  const index = Math.max(0, Math.min(questionNumber - 1, MOTIVATIONAL_PHRASES.length - 1));
  return MOTIVATIONAL_PHRASES[index] || MOTIVATIONAL_PHRASES[0];
}

/**
 * Returns a milestone encouraging message based on completion percentage.
 */
export function getProgressMilestoneMessage(percentage: number): string {
  if (percentage === 0) return "¡Comienza con calma y confianza!";
  if (percentage < 25) return "¡Excelente arranque! Mantén la concentración.";
  if (percentage < 50) return "¡Buen avance! Cada respuesta suma a tu éxito.";
  if (percentage < 75) return "¡Más del 50% completado! Estás en racha positiva.";
  if (percentage < 100) return "¡Recta final! No te rindas, casi lo logras.";
  return "¡100% completado! Excelente demostración de perseverancia.";
}
